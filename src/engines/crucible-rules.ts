export function packCounts(): { tf: number; docker: number; total: number } {
  let tf = 0;
  let docker = 0;
  for (const r of V1_RULEPACK) {
    if (r.ruleId.startsWith('CRUCIBLE.TF.')) tf++;
    else if (r.ruleId.startsWith('CRUCIBLE.DOCKER.')) docker++;
  }
  return { tf, docker, total: V1_RULEPACK.length };
}
