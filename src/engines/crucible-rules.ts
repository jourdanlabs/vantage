function openCidrPort(port: number): RulePredicate[][] {
  const from: RulePredicate = { attributePath: 'from_port', condition: 'lte', value: port };
  const to: RulePredicate = { attributePath: 'to_port', condition: 'gte', value: port };
  const protoAll: RulePredicate = { attributePath: 'protocol', condition: 'equals', value: '-1' };
  const c4: RulePredicate = { attributePath: 'cidr_blocks', condition: 'contains', value: '0.0.0.0/0' };
  const c6: RulePredicate = { attributePath: 'ipv6_cidr_blocks', condition: 'contains', value: '::/0' };
  const v4: RulePredicate = { attributePath: 'cidr_ipv4', condition: 'contains', value: '0.0.0.0/0' };
  const v6: RulePredicate = { attributePath: 'cidr_ipv6', condition: 'contains', value: '::/0' };
  return [
    [c4, from, to],
    [c6, from, to],
    [c4, protoAll],
    [c6, protoAll],
    [v4, from, to],
    [v6, from, to],
    [v4, protoAll],
    [v6, protoAll],
  ];
}

function openCidrAny(): RulePredicate[][] {
  const protoAll: RulePredicate = { attributePath: 'protocol', condition: 'equals', value: '-1' };
  const from0: RulePredicate = { attributePath: 'from_port', condition: 'equals', value: 0 };
  const toAll: RulePredicate = { attributePath: 'to_port', condition: 'in', value: [0, 65535] };
  const c4: RulePredicate = { attributePath: 'cidr_blocks', condition: 'contains', value: '0.0.0.0/0' };
  const c6: RulePredicate = { attributePath: 'ipv6_cidr_blocks', condition: 'contains', value: '::/0' };
  const v4: RulePredicate = { attributePath: 'cidr_ipv4', condition: 'contains', value: '0.0.0.0/0' };
  const v6: RulePredicate = { attributePath: 'cidr_ipv6', condition: 'contains', value: '::/0' };
  return [
    [c4, protoAll],
    [c6, protoAll],
    [v4, protoAll],
    [v6, protoAll],
    [c4, from0, toAll],
    [c6, from0, toAll],
    [v4, from0, toAll],
    [v6, from0, toAll],
  ];
}

